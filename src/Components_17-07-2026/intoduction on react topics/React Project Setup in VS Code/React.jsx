// node -v
// npm -v


// Step 2: Create a React Project
// Open VS Code.
// Open the terminal:
// Terminal → New Terminal
// Run:
// npm create vite@latest my-react-app
// Select:
// React
// Then select:
// JavaScript
// Go inside the project:
// cd my-react-app
// Install packages:
// npm install
// Start the application:
// npm run dev
// You will get a local URL such as:
// http://localhost:5173
// Open it in your browser.

