// Adding--Adding elements means inserting new values into an array.
// Removing--Removing elements means deleting values from an array.


//push-- add at end
let fruits=["apple","banana","manago"]
fruits.push("grapes")
console.log(fruits)



//unshift--add at start
let fruits1=["apple","banana","grapes"]
fruits1.unshift("mango")
console.log(fruits1)

//pop-remove at end
let fruits2=["apple","banana","grapes"]
fruits2.pop()
console.log(fruits2)


//shift--removing at start
let fruits3=["apple","banana","grapes"]
fruits3.shift()
console.log(fruits3)